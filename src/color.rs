/// Excel の色を表す型
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct XlsColor {
    pub red: u8,
    pub green: u8,
    pub blue: u8,
}

impl XlsColor {
    pub const fn rgb(red: u8, green: u8, blue: u8) -> Self {
        Self { red, green, blue }
    }

    /// #RRGGBB 形式の文字列を返す
    pub fn to_hex(&self) -> String {
        format!("#{:02X}{:02X}{:02X}", self.red, self.green, self.blue)
    }

    // 定義済みカラー定数
    pub const BLACK: XlsColor = XlsColor::rgb(0, 0, 0);
    pub const WHITE: XlsColor = XlsColor::rgb(255, 255, 255);
    pub const RED: XlsColor = XlsColor::rgb(255, 0, 0);
    pub const GREEN: XlsColor = XlsColor::rgb(0, 128, 0);
    pub const BLUE: XlsColor = XlsColor::rgb(0, 0, 255);
    pub const YELLOW: XlsColor = XlsColor::rgb(255, 255, 0);
    pub const MAGENTA: XlsColor = XlsColor::rgb(255, 0, 255);
    pub const CYAN: XlsColor = XlsColor::rgb(0, 255, 255);
}

impl std::fmt::Display for XlsColor {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.to_hex())
    }
}

