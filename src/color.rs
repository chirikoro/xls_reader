/// パレットインデックスから色を解決する
pub fn resolve_color_index(index: u16, palette: &[(u8, u8, u8); 56]) -> Option<XlsColor> {
    match index {
        0x00 => None, // No color / automatic (EGA Black but used as "default")
        0x01 => Some(XlsColor::WHITE), // EGA White (automatic background)
        0x08..=0x3F => {
            let i = (index - 0x08) as usize;
            let (r, g, b) = palette[i];
            Some(XlsColor::rgb(r, g, b))
        }
        0x40 => Some(XlsColor::rgb(0, 0, 0)),       // Default foreground (system)
        0x41 => Some(XlsColor::rgb(255, 255, 255)),   // Default background (system)
        0x43 => None, // System foreground (text)
        0x7F => None, // Automatic color
        _ => None,
    }
}
